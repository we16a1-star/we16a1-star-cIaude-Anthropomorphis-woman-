// 存檔裡的角色卡一律經過這裡：非物件一律視為「未自訂」（回預設卡）；
// 文字去頭尾空白並限制長度；整格／整段留空的項目直接丟掉；上限 8 格、12 段。
const sheetText = (value, max) => {
  const text = typeof value === 'string' || typeof value === 'number' ? String(value) : '';
  return text.trim().slice(0, max);
};
export function normalizeCharacterSheet(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return null;
  const stats = (Array.isArray(value.stats) ? value.stats : [])
    .map(item => ({ label: sheetText(item && item.label, 30), value: sheetText(item && item.value, 200) }))
    .filter(item => item.label || item.value)
    .slice(0, 8);
  const sections = (Array.isArray(value.sections) ? value.sections : [])
    .map(item => ({ title: sheetText(item && item.title, 40), body: sheetText(item && item.body, 4000) }))
    .filter(item => item.title || item.body)
    .slice(0, 12);
  return { tagline: sheetText(value.tagline, 120), quote: sheetText(value.quote, 600), stats, sections };
}

